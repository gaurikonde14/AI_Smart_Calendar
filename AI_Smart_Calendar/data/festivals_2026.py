def get_festivals_by_category(category):
    return [
        festival
        for festival in FESTIVALS_2026
        if festival["category"].lower() == category.lower()
    ]


def get_festival_by_date(date):
    return [
        festival
        for festival in FESTIVALS_2026
        if festival["date"] == date
    ]


